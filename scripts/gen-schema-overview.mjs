/**
 * Generiert einen menschenlesbaren Überblick JE Zod-Schema und schreibt ihn als
 * auto-generierten Kommentarblock an den Kopf jeder `src/lib/schemas/*.ts`.
 *
 * Die Zod-Schemas bleiben die Single Source of Truth — dieser Block ist nur eine
 * abgeleitete, scannbare Sicht (Feld : Typ = Default — Beschreibung). Er wird aus
 * dem JSON-Schema (io:'input') gerendert, das Zod selbst liefert; `.describe()`
 * landet als Beschreibung, `.default()` als Default, Optionales als `?`.
 *
 *   npm run schema:overview          # schreibt/aktualisiert die Blöcke
 *   npm run schema:overview -- --check   # exit 1, wenn ein Block veraltet ist (CI/Gate)
 *
 * Läuft in WSL: lädt die TS-Schemas über eine minimale Vite-Instanz (configFile:false,
 * ohne SvelteKit-Plugins) — kein tsx/vitest nötig.
 */
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { createServer } from 'vite';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SCHEMA_DIR = join(ROOT, 'src/lib/schemas');
const CHECK = process.argv.includes('--check');

const BEGIN = '//#region schema-overview (auto-generated by `npm run schema:overview` — do not edit)';
const END = '//#endregion schema-overview';

// ── Rendering: JSON-Schema-Knoten → kompakte Zeilen ──────────────────────────
const TYPE = { integer: 'int', number: 'number', boolean: 'bool', string: 'string' };

function typeLabel(node) {
  if (!node || typeof node !== 'object') return 'any';
  if (node.const !== undefined) return JSON.stringify(node.const);
  if (Array.isArray(node.enum)) return 'enum(' + node.enum.map((v) => JSON.stringify(v)).join('|') + ')';
  if (Array.isArray(node.anyOf)) return node.anyOf.map(typeLabel).join(' | ');
  const t = node.type;
  if (Array.isArray(t)) return t.map((x) => TYPE[x] || x).join('|');
  if (t === 'array') return typeLabel(node.items) + '[]';
  if (t === 'object') return '{…}';
  return TYPE[t] || t || 'any';
}

function desc(node) {
  if (!node?.description) return '';
  const d = node.description.replace(/\s+/g, ' ').trim();
  return d.length > 90 ? d.slice(0, 89) + '…' : d;
}

function renderFields(node, indent, out) {
  const props = node.properties || {};
  const required = new Set(node.required || []);
  for (const [key, sub] of Object.entries(props)) {
    renderField(key + (required.has(key) ? '' : '?'), sub, indent, out);
  }
}

function renderField(label, sub, indent, out) {
  const pad = '  '.repeat(indent);
  if (sub?.type === 'object' && sub.properties) {
    out.push(`${pad}${label}:`);
    renderFields(sub, indent + 1, out);
    return;
  }
  if (sub?.type === 'array' && sub.items?.type === 'object' && sub.items.properties) {
    out.push(`${pad}${label}[]:`);
    renderFields(sub.items, indent + 1, out);
    return;
  }
  let line = `${pad}${label} : ${typeLabel(sub)}`;
  if (sub?.default !== undefined) line += ` = ${JSON.stringify(sub.default)}`;
  const d = desc(sub);
  if (d) line += `  — ${d}`;
  out.push(line);
}

function renderSchema(name, node) {
  // Objekt-Union (z.B. discriminatedUnion) → je Variante eine kompakte Zeile.
  if (Array.isArray(node.anyOf) && node.anyOf.every((b) => b?.type === 'object')) {
    const out = [`${name}  (union)`];
    for (const branch of node.anyOf) {
      const parts = Object.entries(branch.properties || {}).map(([k, v]) =>
        v.const !== undefined ? JSON.stringify(v.const) : `${k}:${typeLabel(v)}`,
      );
      out.push('  • ' + parts.join(' · '));
    }
    return out;
  }
  if (node.type === 'object' && node.properties) {
    const out = [name];
    renderFields(node, 1, out);
    return out;
  }
  return [`${name} : ${typeLabel(node)}`];
}

// ── Datei-Handling: Block einfügen/ersetzen ──────────────────────────────────
function buildBlock(lines) {
  const body = lines.map((l) => `// │ ${l}`.trimEnd());
  return [BEGIN, '// ┌─ SCHEMA OVERVIEW', ...body, '// └─', END].join('\n');
}

/** Ersetzt einen vorhandenen Block oder fügt ihn vor dem ersten `import` ein. */
function applyBlock(source, block) {
  const b = source.indexOf(BEGIN);
  if (b !== -1) {
    const e = source.indexOf(END, b);
    const endLine = source.indexOf('\n', e);
    return source.slice(0, b) + block + source.slice(endLine === -1 ? source.length : endLine);
  }
  const lines = source.split('\n');
  const idx = lines.findIndex((l) => l.startsWith('import '));
  const at = idx === -1 ? lines.length : idx;
  lines.splice(at, 0, block, '');
  return lines.join('\n');
}

// ── Main ─────────────────────────────────────────────────────────────────────
const server = await createServer({
  configFile: false,
  server: { middlewareMode: true },
  appType: 'custom',
  logLevel: 'error',
  optimizeDeps: { noDiscovery: true },
});
const { z } = await server.ssrLoadModule('zod');

const files = readdirSync(SCHEMA_DIR)
  .filter((f) => f.endsWith('.ts') && f !== 'shared.ts')
  .sort();

let stale = 0;
let written = 0;

for (const file of files) {
  const path = join(SCHEMA_DIR, file);
  const source = readFileSync(path, 'utf8');
  const mod = await server.ssrLoadModule('/src/lib/schemas/' + file);

  // Schemas in QUELLTEXT-Reihenfolge (nicht alphabetisch), damit der Block der
  // Datei folgt. `export const XSchema =` liefert die Namen in Reihenfolge.
  const order = [...source.matchAll(/export const (\w+)\s*=/g)].map((m) => m[1]);
  const schemas = order.filter((n) => typeof mod[n]?.safeParse === 'function');
  if (schemas.length === 0) continue;

  const lines = [];
  for (const name of schemas) {
    const json = z.toJSONSchema(mod[name], { target: 'draft-2020-12', io: 'input', unrepresentable: 'any' });
    lines.push(...renderSchema(name, json), '');
  }
  while (lines.at(-1) === '') lines.pop();

  const next = applyBlock(source, buildBlock(lines));
  if (next === source) continue;

  if (CHECK) {
    stale++;
    console.error(`✗ veraltet: src/lib/schemas/${file}`);
  } else {
    writeFileSync(path, next);
    written++;
    console.log(`✓ ${file} (${schemas.length} Schemas)`);
  }
}

await server.close();

if (CHECK && stale > 0) {
  console.error(`\n${stale} Schema-Datei(en) veraltet — bitte \`npm run schema:overview\` laufen lassen.`);
  process.exit(1);
}
if (!CHECK) console.log(`\nFertig: ${written} Datei(en) aktualisiert.`);
